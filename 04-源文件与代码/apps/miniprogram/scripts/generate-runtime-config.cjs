const { createHash } = require("node:crypto");
const {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  unlinkSync,
  writeFileSync
} = require("node:fs");
const path = require("node:path");

const configDirectory = path.resolve(
  __dirname,
  "..",
  "miniprogram",
  "config"
);
const targetPaths = {
  javascript: path.join(configDirectory, "runtime.generated.js"),
  typescript: path.join(configDirectory, "runtime.generated.ts")
};

function isPrivateIpv4(hostname) {
  const parts = hostname.split(".").map(Number);
  if (
    parts.length !== 4 ||
    parts.some((part) => (
      !Number.isInteger(part) || part < 0 || part > 255
    ))
  ) return false;
  return parts[0] === 10 ||
    (parts[0] === 172 && parts[1] >= 16 && parts[1] <= 31) ||
    (parts[0] === 192 && parts[1] === 168);
}

function hasOriginOnly(parsed) {
  return !parsed.username && !parsed.password &&
    parsed.pathname === "/" && !parsed.search && !parsed.hash;
}

function hasStandardIpv4Text(value, parsed) {
  const authority = value.slice("http://".length).split(/[/?#]/, 1)[0];
  const rawHostname = authority.split(":", 1)[0];
  return rawHostname === parsed.hostname && rawHostname.split(".").every(
    (part) => /^(0|[1-9][0-9]{0,2})$/.test(part)
  );
}

function buildRuntimeConfig(environment) {
  const mode = environment.PHOTO_AI_APP_MODE;
  if (mode !== "local" && mode !== "acceptance" && mode !== "production") {
    throw new Error("INVALID_PHOTO_AI_APP_MODE");
  }

  if (mode === "local") {
    return { mode, apiBase: "http://127.0.0.1:3100" };
  }

  let parsed;
  try {
    parsed = new URL(environment.PHOTO_AI_API_BASE ?? "");
  } catch {
    throw new Error("INVALID_PHOTO_AI_API_BASE");
  }

  const isHttpsOrigin = parsed.protocol === "https:";
  const apiBase = environment.PHOTO_AI_API_BASE ?? "";
  const isAcceptanceLanOrigin = mode === "acceptance" &&
    parsed.protocol === "http:" &&
    hasStandardIpv4Text(apiBase, parsed) &&
    isPrivateIpv4(parsed.hostname);
  if (!hasOriginOnly(parsed) || (!isHttpsOrigin && !isAcceptanceLanOrigin)) {
    throw new Error("INVALID_PHOTO_AI_API_BASE");
  }

  return { mode, apiBase: parsed.origin };
}

function generationFor(config) {
  return createHash("sha256")
    .update(JSON.stringify([config.mode, config.apiBase]))
    .digest("hex");
}

function renderRuntimeSources(config) {
  const header = "// Generated by scripts/generate-runtime-config.cjs. Do not edit or commit.\n" +
    `// Generation: ${generationFor(config)}\n`;
  const body =
    "export const runtimeConfig = Object.freeze({\n" +
    `  mode: ${JSON.stringify(config.mode)},\n` +
    `  apiBase: ${JSON.stringify(config.apiBase)}\n`;
  return {
    javascript: header + body + "});\n",
    typescript: header + body + "} as const);\n"
  };
}

function readRecognizedSource(targetPath) {
  if (!existsSync(targetPath)) return undefined;
  const source = readFileSync(targetPath, "utf8");
  const generation = source.match(/^\/\/ Generation: ([0-9a-f]{64})$/m)?.[1];
  const mode = source.match(/^  mode: ("(?:[^"\\]|\\.)*"),$/m)?.[1];
  const apiBase = source.match(/^  apiBase: ("(?:[^"\\]|\\.)*")$/m)?.[1];
  if (!generation || !mode || !apiBase) return undefined;
  try {
    return {
      source,
      generation,
      config: {
        mode: JSON.parse(mode),
        apiBase: JSON.parse(apiBase)
      }
    };
  } catch {
    return undefined;
  }
}

function hasValidRuntimeConfigPair() {
  const javascript = readRecognizedSource(targetPaths.javascript);
  const typescript = readRecognizedSource(targetPaths.typescript);
  if (!javascript || !typescript) return false;

  let normalized;
  try {
    normalized = buildRuntimeConfig({
      PHOTO_AI_APP_MODE: typescript.config.mode,
      PHOTO_AI_API_BASE: typescript.config.apiBase
    });
  } catch {
    return false;
  }

  const expectedGeneration = generationFor(normalized);
  const expectedSources = renderRuntimeSources(normalized);
  return javascript.generation === expectedGeneration &&
    typescript.generation === expectedGeneration &&
    javascript.config.mode === normalized.mode &&
    javascript.config.apiBase === normalized.apiBase &&
    typescript.config.mode === normalized.mode &&
    typescript.config.apiBase === normalized.apiBase &&
    javascript.source === expectedSources.javascript &&
    typescript.source === expectedSources.typescript;
}

function writeRuntimeConfig(config) {
  mkdirSync(configDirectory, { recursive: true });
  const sources = renderRuntimeSources(config);
  const nonce = `${process.pid}.${Date.now()}`;
  const temporaryPaths = {
    javascript: `${targetPaths.javascript}.${nonce}.tmp`,
    typescript: `${targetPaths.typescript}.${nonce}.tmp`
  };
  const rollbackPath = `${targetPaths.typescript}.${nonce}.rollback`;
  const previousTypescript = existsSync(targetPaths.typescript)
    ? readFileSync(targetPaths.typescript, "utf8")
    : undefined;
  try {
    writeFileSync(temporaryPaths.typescript, sources.typescript, {
      encoding: "utf8",
      flag: "wx"
    });
    writeFileSync(temporaryPaths.javascript, sources.javascript, {
      encoding: "utf8",
      flag: "wx"
    });
    renameSync(temporaryPaths.typescript, targetPaths.typescript);
    try {
      renameSync(temporaryPaths.javascript, targetPaths.javascript);
    } catch (error) {
      try {
        if (previousTypescript === undefined) {
          if (existsSync(targetPaths.typescript)) unlinkSync(targetPaths.typescript);
        } else {
          writeFileSync(rollbackPath, previousTypescript, {
            encoding: "utf8",
            flag: "wx"
          });
          renameSync(rollbackPath, targetPaths.typescript);
        }
      } catch {
        // Preserve the original replacement error; --ensure repairs any split pair.
      }
      throw error;
    }
  } finally {
    for (const temporaryPath of [...Object.values(temporaryPaths), rollbackPath]) {
      if (existsSync(temporaryPath)) unlinkSync(temporaryPath);
    }
  }
}

function run(argv, environment) {
  if (argv.length !== 1) throw new Error("INVALID_RUNTIME_CONFIG_COMMAND");
  const [command] = argv;
  if (command === "--ensure") {
    if (!hasValidRuntimeConfigPair()) {
      writeRuntimeConfig(buildRuntimeConfig({ PHOTO_AI_APP_MODE: "local" }));
    }
    return;
  }
  if (command === "--local") {
    writeRuntimeConfig(buildRuntimeConfig({ PHOTO_AI_APP_MODE: "local" }));
    return;
  }
  if (command === "--from-env") {
    if (!environment.PHOTO_AI_APP_MODE) {
      throw new Error("INVALID_PHOTO_AI_APP_MODE");
    }
    if (!environment.PHOTO_AI_API_BASE) {
      throw new Error("INVALID_PHOTO_AI_API_BASE");
    }
    writeRuntimeConfig(buildRuntimeConfig(environment));
    return;
  }
  throw new Error("INVALID_RUNTIME_CONFIG_COMMAND");
}

module.exports = { buildRuntimeConfig, renderRuntimeSources };

if (require.main === module) {
  try {
    run(process.argv.slice(2), process.env);
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : error}\n`);
    process.exitCode = 1;
  }
}
